use std::env;
use std::fs;
use std::path::Path;

mod quarto_templates; // Load helper function for quarto templates
mod paper_templates; // Optional: upload docx documents if writing a paper
mod code_base; // Add code base
mod decisions; // Add DECISIONS.md template

/// A target is safe if it does not exist yet, or is an empty directory.
fn is_safe_target(root: &Path) -> std::io::Result<bool> {
    if !root.exists() {
        return Ok(true);
    }
    if !root.is_dir() {
        return Ok(false); // a file with that name exists
    }
    Ok(fs::read_dir(root)?.next().is_none())
}

fn main() -> std::io::Result<()> {

    // Parse arguments: bio-init-dir <project-name> [--papers]
    let args: Vec<String> = env::args().collect();
    let mut project_name: Option<&String> = None;
    let mut include_papers = false;

    for arg in &args[1..] {
        match arg.as_str() {
            "--papers" => include_papers = true,
            option if option.starts_with("--") => {
                eprintln!("Error: Unknown option '{}'.", option);
                eprintln!("Usage: bio-init-dir <project-name> [--papers]");
                std::process::exit(1);
            }
            _ => {
                if project_name.is_some() {
                    eprintln!("Error: More than one project name given.");
                    eprintln!("Usage: bio-init-dir <project-name> [--papers]");
                    std::process::exit(1);
                }
                project_name = Some(arg);
            }
        }
    }

    let project_name = match project_name {
        Some(name) => name,
        None => {
            eprintln!("Error: Please provide a project name.");
            eprintln!("Usage: bio-init-dir <project-name> [--papers]");
            std::process::exit(1);
        }
    };

    let root = Path::new(project_name);

    // Safety check: stop before creating anything
    if !is_safe_target(root)? {
        eprintln!(
            "Error: '{}' already exists and is not empty. Nothing was created.",
            project_name
        );
        std::process::exit(1);
    }

    // Define subdirectories
    let directories = vec![
        root.join("inputs"),
        root.join("intermediary"),
        root.join("outputs"),
        root.join("src"),
        root.join("documents"),
        root.join("documents/reports"),
        root.join("documents/presentations"),
        root.join("documents/extras"),
        root.join("documents/posters"),
        root.join("documents/papers"),
        root.join("documents/papers_draft"),
        root.join("plots")
    ];

    println!("Initializing project structure in: {}/", project_name);

    // Create directories
    for dir in directories {
        fs::create_dir_all(&dir)?;
        println!(" Created: {}", dir.display());
    }

    // Generate default README file
    let readme_path = root.join("README.md");
    let readme_content = format!(
        "# {}\n\n\
        ## Overview\n\
        Bioinformatics project initialized on {}.\n\n\
        ## Structure\n\
        - `inputs/`: Raw input data.\n\
        - `intermediary/`: Intermediate files generated during parsing and standardization.\n\
        - `outputs/`: Results of the analysis.\n\
        - `src/`: Source code and analysis scripts.\n\
        - `documents/`: Written material related to the project.\n\
        \x20 - `reports/`: Reports.\n\
        \x20 - `presentations/`: Slides and presentations.\n\
        \x20 - `posters/`: Posters.\n\
        \x20 - `extras/`: Any other supporting documents.\n\
        - `plots/`: Figures and plots generated by the analysis.\n",
        project_name,
        chrono::Local::now().format("%Y-%m-%d")
    );

    fs::write(readme_path, readme_content)?;
    println!(" Created: {}/README.md", project_name);

    code_base::create_code_base(root)?;
    
    decisions::create_decisions_file(root)?;

    quarto_templates::create_quarto_templates(root)?;

    if include_papers {
        paper_templates::create_paper_templates(root)?;
    }

    println!("\nProject created successfully!");

    Ok(())
}